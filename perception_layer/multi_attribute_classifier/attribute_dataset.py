"""
PyTorch Dataset for FashionCLIP pseudo-labeled attribute samples.

Expects .pt files generated by pseudo_label_generation.py.
"""

import os
from pathlib import Path
from typing import Any

import torch
from torch.utils.data import Dataset


class AttributeDataset(Dataset):
    def __init__(
        self,
        root: str,
        category_id_offset: int = 0,
        strict: bool = True,
    ):
        self.root = Path(root)
        self.category_id_offset = int(category_id_offset)
        self.strict = bool(strict)

        self.files = [
            self.root / f
            for f in sorted(os.listdir(self.root))
            if f.endswith(".pt")
        ]

        if not self.files:
            raise RuntimeError(f"No .pt files found in {self.root}")

    def __len__(self) -> int:
        return len(self.files)

    @staticmethod
    def _safe_load(path: Path) -> dict[str, Any]:
        try:
            try:
                return torch.load(path, weights_only=True)
            except TypeError:
                return torch.load(path)
        except Exception as exc:
            raise RuntimeError(f"Could not load sample: {path}") from exc

    @staticmethod
    def _normalize_soft_label(label: torch.Tensor, expected_size: int, path: Path, key: str) -> torch.Tensor:
        label = label.float().flatten()

        if label.numel() != expected_size:
            raise ValueError(
                f"Expected {key} label size {expected_size}, got {label.numel()} in {path}"
            )

        if torch.isnan(label).any():
            raise ValueError(f"NaNs in {key} label: {path}")

        label = label.clamp_min(0.0)
        total = label.sum()

        if total <= 1e-8:
            return torch.full((expected_size,), 1.0 / expected_size, dtype=torch.float32)

        return label / total

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        path = self.files[idx]
        sample = self._safe_load(path)

        required = [
            "image",
            "category_id",
            "fit",
            "style",
            "weather_warmth",
            "formality_score",
        ]

        for key in required:
            if key not in sample:
                raise KeyError(f"Missing key '{key}' in {path}")

        image = sample["image"].float()

        if image.shape != (3, 224, 224):
            raise ValueError(f"Expected image shape (3, 224, 224), got {tuple(image.shape)} in {path}")

        if torch.isnan(image).any():
            raise ValueError(f"NaNs in image tensor: {path}")

        category_id = int(sample["category_id"]) + self.category_id_offset

        if category_id < 0:
            raise ValueError(f"Invalid category_id {category_id} after offset in {path}")

        fit = self._normalize_soft_label(sample["fit"], 3, path, "fit")
        style = self._normalize_soft_label(sample["style"], 4, path, "style")

        weather = float(sample["weather_warmth"])
        formality = float(sample["formality_score"])

        weather = max(0.0, min(1.0, weather))
        formality = max(0.0, min(1.0, formality))

        return {
            "image": image,
            "category_id": torch.tensor(category_id, dtype=torch.long),
            "fit": fit,
            "style": style,
            "weather_warmth": torch.tensor(weather, dtype=torch.float32),
            "formality_score": torch.tensor(formality, dtype=torch.float32),
        }